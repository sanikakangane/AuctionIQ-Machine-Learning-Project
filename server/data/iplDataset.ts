// Historical labelled IPL auction training samples (2023-2026 matched records)
// Used to train both StandardLinearRegression and RandomForestRegressor on the 16-feature vector.
function sampleFrom(
  runs: number,
  balls_faced: number,
  fours: number,
  sixes: number,
  batting_matches: number,
  dismissals: number,
  balls_bowled: number,
  wickets: number,
  runs_conceded: number,
  bowling_matches: number,
  matches: number,
  soldPriceCr: number
): TrainingSample {
  const strike_rate = balls_faced > 0 ? Number(((runs / balls_faced) * 100).toFixed(2)) : 0;
  const batting_average = dismissals > 0 ? Number((runs / dismissals).toFixed(2)) : runs;
  const overs_bowled = Number((balls_bowled / 6).toFixed(1));
  const economy = balls_bowled > 0 ? Number((runs_conceded / (balls_bowled / 6)).toFixed(2)) : 0;
  const runs_per_match = matches > 0 ? Number((runs / matches).toFixed(2)) : 0;

  return {
    features: {
      runs,
      balls_faced,
      fours,
      sixes,
      batting_matches,
      strike_rate,
      batting_average,
      dismissals,
      balls_bowled,
      wickets,
      runs_conceded,
      overs_bowled,
      economy,
      bowling_matches,
      matches,
      runs_per_match,
    },
    soldPriceCr,
  };
}

