function slugify(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

interface RawPlayerSeed {
  name: string;
  role: PlayerRecord['role'];
  team2026: string | null;
  teamCode: string | null;
  previousTeams: string[];
  has_2026_stats: boolean;
  statsAvailabilityNote?: string;
  runs?: number | null;
  balls_faced?: number | null;
  fours?: number | null;
  sixes?: number | null;
  batting_matches?: number | null;
  dismissals?: number | null;
  balls_bowled?: number | null;
  wickets?: number | null;
  runs_conceded?: number | null;
  bowling_matches?: number | null;
  matches?: number | null;
}

function buildFeatures(seed: RawPlayerSeed): {
  features: FeatureVector;
  bowlingAverage: number | null;
} {
  if (!seed.has_2026_stats) {
    return {
      features: {
        runs: null,
        balls_faced: null,
        fours: null,
        sixes: null,
        batting_matches: null,
        strike_rate: null,
        batting_average: null,
        dismissals: null,
        balls_bowled: null,
        wickets: null,
        runs_conceded: null,
        overs_bowled: null,
        economy: null,
        bowling_matches: null,
        matches: null,
        runs_per_match: null,
      },
      bowlingAverage: null,
    };
  }

  const runs = seed.runs ?? 0;
  const balls_faced = seed.balls_faced ?? 0;
  const fours = seed.fours ?? 0;
  const sixes = seed.sixes ?? 0;
  const batting_matches = seed.batting_matches ?? 0;
  const dismissals = seed.dismissals ?? 0;
  const balls_bowled = seed.balls_bowled ?? 0;
  const wickets = seed.wickets ?? 0;
  const runs_conceded = seed.runs_conceded ?? 0;
  const bowling_matches = seed.bowling_matches ?? 0;
  const matches = seed.matches ?? Math.max(batting_matches, bowling_matches);

  const strike_rate = balls_faced > 0 ? Number(((runs / balls_faced) * 100).toFixed(2)) : 0;
  const batting_average =
    dismissals > 0 ? Number((runs / dismissals).toFixed(2)) : runs > 0 ? runs : 0;
  const overs_bowled = Number((balls_bowled / 6).toFixed(1));
  const economy = balls_bowled > 0 ? Number((runs_conceded / (balls_bowled / 6)).toFixed(2)) : 0;
  const runs_per_match = matches > 0 ? Number((runs / matches).toFixed(2)) : 0;
  const bowlingAverage = wickets > 0 ? Number((runs_conceded / wickets).toFixed(2)) : null;

  return {
    features: {
      runs,
      balls_faced,
      fours,
      sixes,
      batting_matches,
      strike_rate,
      batting_average,
      dismissals,
      balls_bowled,
      wickets,
      runs_conceded,
      overs_bowled,
      economy,
      bowling_matches,
      matches,
      runs_per_match,
    },
    bowlingAverage,
  };
}

